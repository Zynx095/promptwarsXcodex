export const LANGUAGES = [
  { code: 'en', label: 'English' },
  { code: 'kn', label: 'ಕನ್ನಡ' },
] as const;
export type Lang = (typeof LANGUAGES)[number]['code'];

const dictionaries: Record<Lang, Dictionary> = { en, kn };
const STORAGE_KEY = 'fairshift.lang';

function interpolate(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

interface I18n {
  lang: Lang;
  locale: string;
  setLang: (l: Lang) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  /** Translates an industry category, falling back to the configured English label. */
  category: (kind: 'hazard' | 'topic', key: string, fallback: string) => string;
}

const I18nContext = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'kn') return stored;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith('kn') ? 'kn' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage unavailable */
    }
  }, []);
  const value = useMemo<I18n>(
    () => ({
      lang,
      locale: lang === 'kn' ? 'kn-IN' : 'en-IN',
      setLang,
      t: (key, vars) => interpolate(dictionaries[lang][key] ?? en[key], vars),
      category: (kind, key, fallback) => (lang === 'kn' ? (knCategories[`${kind}.${key}`] ?? fallback) : fallback),
    }),
    [lang, setLang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}
